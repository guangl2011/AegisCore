"""Deterministic 100-trajectory benchmark corpus for SCAL.

Each trajectory is a seeded, reproducible sequence of task commands
(``MoveTo`` / ``FollowPath`` / ``SetBlade`` / ``Dock``) that round-robins
over the three reference chassis. The corpus is generated by ``random.Random``
with a fixed seed — no wall clock, no hypothesis generation — so every CI run
and every harness invocation exercises byte-identical commands.

Commands are expressed against the origin context pose: each command is
translated independently (composition/integration of executed motion is the
simulator's concern, not the corpus's). Generator bounds keep every command
inside its chassis' envelope, so translation must succeed for all of them —
a translation that raises or emits an out-of-limit actuator value on a corpus
trajectory is a bug, and the property tests treat it as one.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass

from aegiscore.core.model import Kinematics, TaskCommand
from aegiscore.scal.kinematics import max_curvature_for_speed
from aegiscore.scal.profiles import REFERENCE_PROFILES, ROLE_BLADE, ScalProfile
from aegiscore.scal.translator import (
    NOMINAL_DRIVE_MPS,
    PRIMITIVE_DOCK,
    PRIMITIVE_FOLLOW_PATH,
    PRIMITIVE_MOVE_TO,
    PRIMITIVE_SET_BLADE,
    _cap_speed_for_curvature,
)

CORPUS_SEED = 20261102
CORPUS_SIZE = 100
_COMMANDS_PER_TRAJECTORY = (6, 12)


@dataclass(frozen=True)
class Trajectory:
    """One benchmark trajectory: a sequence of task commands for one chassis."""

    trajectory_id: str
    profile_name: str
    commands: tuple[TaskCommand, ...]


def _speed_cap(profile: ScalProfile) -> float:
    """Sampling speed: stays inside the linear-speed box with headroom."""
    return 0.9 * profile.core.max_linear_speed


def _curvature_cap(profile: ScalProfile) -> float:
    """Sampling curvature bound: 80% of the family bound at the speed cap."""
    v = _speed_cap(profile)
    return 0.8 * max_curvature_for_speed(profile, v)


def _sample_move_to(rng: random.Random, profile: ScalProfile) -> TaskCommand:
    if profile.kinematics is Kinematics.ACKERMANN:
        # The required arc curvature is kappa = 2*sin(bearing)/dist, so bound
        # the bearing by the curvature cap and keep the target ahead of the axle.
        dist = rng.uniform(2.5, 15.0)
        bearing_cap = math.asin(min(1.0, 0.5 * _curvature_cap(profile) * dist))
        bearing = rng.uniform(-bearing_cap, bearing_cap)
    else:
        dist = rng.uniform(0.5, 15.0)
        bearing = rng.uniform(-2.5, 2.5)
    theta = rng.uniform(-math.pi, math.pi)
    return TaskCommand(
        primitive=PRIMITIVE_MOVE_TO,
        params={
            "x": dist * math.cos(bearing),
            "y": dist * math.sin(bearing),
            "theta": theta,
        },
        issued_us=0,
    )


def _sample_follow_path(rng: random.Random, profile: ScalProfile) -> TaskCommand:
    n_segments = rng.randint(1, 3)
    v_nom = min(NOMINAL_DRIVE_MPS, _speed_cap(profile))
    kappa_cap = _curvature_cap(profile)
    params: dict[str, float] = {"n_segments": float(n_segments)}
    for i in range(n_segments):
        params[f"seg{i}_len"] = rng.uniform(0.5, 6.0)
        params[f"seg{i}_curv"] = rng.uniform(-kappa_cap, kappa_cap)
        params[f"seg{i}_speed"] = _cap_speed_for_curvature(profile, v_nom, params[f"seg{i}_curv"])
    return TaskCommand(primitive=PRIMITIVE_FOLLOW_PATH, params=params, issued_us=0)


def _sample_set_blade(rng: random.Random, profile: ScalProfile) -> TaskCommand | None:
    blade_max = profile.geometry.blade_max_speed_rad_s
    if ROLE_BLADE not in profile.core.actuators or blade_max is None:
        return None
    return TaskCommand(
        primitive=PRIMITIVE_SET_BLADE,
        params={"enabled": float(rng.randint(0, 1)), "speed": 0.9 * blade_max * rng.random()},
        issued_us=0,
    )


def _sample_dock(rng: random.Random, profile: ScalProfile) -> TaskCommand:
    if profile.kinematics is Kinematics.ACKERMANN:
        dist = rng.uniform(2.5, 10.0)
        bearing_cap = math.asin(min(1.0, 0.5 * _curvature_cap(profile) * dist))
        bearing = rng.uniform(-bearing_cap, bearing_cap)
    else:
        dist = rng.uniform(1.0, 10.0)
        bearing = rng.uniform(-1.5, 1.5)
    return TaskCommand(
        primitive=PRIMITIVE_DOCK,
        params={"x": dist * math.cos(bearing), "y": dist * math.sin(bearing), "theta": bearing},
        issued_us=0,
    )


def build_corpus(seed: int = CORPUS_SEED, size: int = CORPUS_SIZE) -> list[Trajectory]:
    """Build the deterministic trajectory corpus (100 trajectories by default)."""
    rng = random.Random(seed)
    profile_names = list(REFERENCE_PROFILES)
    corpus: list[Trajectory] = []
    for index in range(size):
        profile_name = profile_names[index % len(profile_names)]
        profile = REFERENCE_PROFILES[profile_name]
        commands: list[TaskCommand] = []

        blade_on = _sample_set_blade(rng, profile)
        if blade_on is not None:
            commands.append(blade_on)

        for _ in range(rng.randint(*_COMMANDS_PER_TRAJECTORY)):
            roll = rng.random()
            if roll < 0.4:
                commands.append(_sample_move_to(rng, profile))
            elif roll < 0.8:
                commands.append(_sample_follow_path(rng, profile))
            else:
                commands.append(_sample_dock(rng, profile))

        if blade_on is not None:
            blade_max = profile.geometry.blade_max_speed_rad_s
            assert blade_max is not None  # blade profiles validated at construction
            commands.append(
                TaskCommand(
                    primitive=PRIMITIVE_SET_BLADE,
                    params={"enabled": 0.0},
                    issued_us=0,
                )
            )
        commands.append(_sample_dock(rng, profile))

        issued_us = 0
        final_commands: list[TaskCommand] = []
        for cmd in commands:
            issued_us += rng.randrange(1_000, 100_000)
            final_commands.append(
                TaskCommand(primitive=cmd.primitive, params=cmd.params, issued_us=issued_us)
            )

        corpus.append(
            Trajectory(
                trajectory_id=f"traj-{index:03d}",
                profile_name=profile_name,
                commands=tuple(final_commands),
            )
        )
    return corpus
